        text(s, p, x + 3f, top + 3f, width - 6f, 10f, label, PdfTypographyRole.OPTIONAL_DECORATIVE, 6.2f, 5.3f,
            align = PdfHorizontalAlignment.CENTER)
        text(s, p, x + 4f, top + 14f, width - 8f, height - 17f, value, PdfTypographyRole.PRIMARY_VALUE, 13f, 10f,
            align = PdfHorizontalAlignment.CENTER)
    }

    private fun tableHeader(
        s: PDPageContentStream,
        p: DesktopPdfRenderingPrimitives,
        x: Float,
        top: Float,
        columns: List<Pair<Float, String>>,
    ) {
        var cursor = x
        columns.forEach { (width, title) ->
            text(s, p, cursor + 2f, top, width - 4f, 18f, title, PdfTypographyRole.OPTIONAL_DECORATIVE, 7f, 6f,
                align = PdfHorizontalAlignment.CENTER)
            cursor += width
        }
        hairline(s, x, top + 20f, cursor, top + 20f)
    }

    private fun tableRow(
        s: PDPageContentStream,
        p: DesktopPdfRenderingPrimitives,
        x: Float,
        top: Float,
        values: List<String>,
        widths: List<Float>,
        index: Int,
    ) {
        shadeRow(s, x, top, widths.sum(), 30f, index)
        var cursor = x
        values.forEachIndexed { i, value ->
            text(
                s, p, cursor + 3f, top + 2f, widths[i] - 6f, 25f, value,
                if (i == 1 || i == 0) PdfTypographyRole.BODY else PdfTypographyRole.COMPACT_TABLE,
                if (i == 1) 8.2f else 7.5f, 6.4f,
                align = if (i == 0 || i == 2) PdfHorizontalAlignment.CENTER else PdfHorizontalAlignment.LEFT,
            )
            cursor += widths[i]
        }
    }

    private fun blankTableRow(s: PDPageContentStream, x: Float, top: Float, width: Float, index: Int) {
        shadeRow(s, x, top, width, 24f, index)
    }

    private fun ruledText(
        s: PDPageContentStream,
        p: DesktopPdfRenderingPrimitives,
        x: Float,
        top: Float,
        width: Float,
        height: Float,
        paragraphs: List<String>,
    ) {
        val rowHeight = 22f
        val rows = (height / rowHeight).toInt()
        repeat(rows) { i -> shadeRow(s, x, top + i * rowHeight, width, rowHeight - 2f, i) }
        paragraphs.forEachIndexed { i, paragraph ->
            val paragraphTop = top + i * 66f + 2f
            text(s, p, x + 4f, paragraphTop, width - 8f, 60f, paragraph, PdfTypographyRole.NOTE_TEXT,
                8.1f, 7f, wrap = true, maxLines = 3, vertical = PdfVerticalAlignment.TOP)
        }
    }

    private fun ruledBands(
        s: PDPageContentStream,
        x: Float,
        top: Float,
        width: Float,
        height: Float,
        rows: Int,
    ) {
        val rowHeight = height / rows
        repeat(rows) { i -> shadeRow(s, x, top + i * rowHeight, width, rowHeight - 2f, i) }
    }

    private fun shadeRow(
        s: PDPageContentStream,
        x: Float,
        top: Float,
        width: Float,
        height: Float,
        index: Int,
    ) {
        if (index % 2 == 0) fillRect(s, x, top, width, height, BAND_FILL)
        hairline(s, x, top + height + 2f, x + width, top + height + 2f)
    }

    private fun grid(
        s: PDPageContentStream,
        x: Float,
        top: Float,
        width: Float,
        height: Float,
        columns: Int,
        rows: Int,
    ) {
        val y = H - top - height
        s.saveGraphicsState()
        s.setStrokingColor(GRID_COLOR)
        s.setLineWidth(0.35f)
        s.addRect(x, y, width, height)
        s.stroke()
        repeat(columns - 1) { i ->
            val xx = x + width * (i + 1) / columns
            s.moveTo(xx, y)
            s.lineTo(xx, y + height)
        }
        repeat(rows - 1) { i ->
            val yy = y + height * (i + 1) / rows
            s.moveTo(x, yy)
            s.lineTo(x + width, yy)
        }
        s.stroke()
        s.restoreGraphicsState()
    }

    private fun trainingMarker(
        s: PDPageContentStream,
