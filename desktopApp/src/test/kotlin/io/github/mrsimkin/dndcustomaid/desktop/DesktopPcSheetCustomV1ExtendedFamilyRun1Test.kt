/**
 * Complete owner-review proof for the Custom-v1 visual family.
 *
 * The five owner-approved Run-7 base pages are generated by the frozen Run-7 QA fixture and then
 * preserved pixel-identically. Six generated purpose-specific extension pages are appended using
 * the owner-authored v1 paper grammar: centered section headings, alternating gray writing bands,
 * thin rules, compact lookup values and generous writable capacity.
 */
class DesktopPcSheetCustomV1ExtendedFamilyRun1Test {
    private val overflowDiagnostics = mutableListOf<String>()

    @Test
    fun rendersCompleteCustomV1FamilyWithAllExtensionRoles() {
        overflowDiagnostics.clear()
        val proofDir = File(requireNotNull(System.getProperty("pcSheetProofDir"))).apply { mkdirs() }

        // Generate the exact approved five-page Run-7 baseline rather than reimplementing it here.
        DesktopPcSheetHybridStrategyRun7Test().rendersCompleteFivePageAllHybridCustomV1Draft()
        val approvedBase = File(proofDir, "hybrid-strategy1-run7-composite.pdf")
        assertTrue(approvedBase.isFile)

        val baselineRenders = Loader.loadPDF(approvedBase).use { doc ->
            val renderer = PDFRenderer(doc)
            (0 until 5).map { renderer.renderImageWithDPI(it, BASELINE_COMPARE_DPI, ImageType.RGB) }
        }

        val output = File(proofDir, "custom-v1-complete-family-extended-run1.pdf")
        val sourceBytes = resource(TEMPLATE).use { it.readBytes() }

        Loader.loadPDF(approvedBase).use { doc ->
            Loader.loadPDF(sourceBytes).use { source ->
                val logoForm = LayerUtility(doc).importPageAsForm(source, 4)
                val fonts = DesktopPdfFontRegistry(doc, CUSTOM_V1_EXTENSION_THEME)
                val p = DesktopPdfRenderingPrimitives(fonts)

                drawCustomStatistics(doc, p, logoForm)
                drawTraits(doc, p, logoForm)
                drawResources(doc, p, logoForm)
                drawInventory(doc, p, logoForm)
                drawSpells(doc, p, logoForm)
                drawNotes(doc, p, logoForm)
            }
            doc.save(output)
        }

        Loader.loadPDF(output).use { doc ->
            assertEquals(11, doc.numberOfPages)
            assertFalse(doc.isEncrypted)
            repeat(doc.numberOfPages) { index ->
                assertEquals(W, doc.getPage(index).mediaBox.width, 0.01f)
                assertEquals(H, doc.getPage(index).mediaBox.height, 0.01f)
            }

            val extracted = PDFTextStripper().getText(doc)
            listOf(
                "EXTENSIÓN - ESTADÍSTICAS PERSONALIZADAS",
                "EXTENSIÓN - RASGOS Y CARACTERÍSTICAS",
                "EXTENSIÓN - RECURSOS Y OPCIONES",
                "EXTENSIÓN - INVENTARIO / EQUIPO",
                "EXTENSIÓN - CONJUROS",
                "EXTENSIÓN - NOTAS",
            ).forEach { title ->
                assertTrue(extracted.contains(title), "Missing Custom-v1 extension title: $title")
            }

            val renderer = PDFRenderer(doc)
            repeat(11) { index ->
                val image = renderer.renderImageWithDPI(index, 180f, ImageType.RGB)
                assertTrue(
                    ImageIO.write(
                        image,
                        "png",
                        File(proofDir, "custom-v1-complete-family-extended-run1-page-${index + 1}.png"),
                    ),
                )
            }

            // Appending extensions must not change one pixel of the frozen five-page baseline.
            repeat(5) { index ->
                val finalImage = renderer.renderImageWithDPI(index, BASELINE_COMPARE_DPI, ImageType.RGB)
                assertImagesEqual(
                    baselineRenders[index],
                    finalImage,
                    "Frozen Custom-v1 base page ${index + 1} changed while adding extensions.",
                )
            }
        }

        if (overflowDiagnostics.isNotEmpty()) {
            File(proofDir, "custom-v1-complete-family-extended-run1-overflows.txt")
                .writeText(overflowDiagnostics.joinToString("\n"))
        }
        check(overflowDiagnostics.isEmpty()) {
            "Custom-v1 Extended Run 1 text overflow(s):\n" + overflowDiagnostics.joinToString("\n")
        }
        assertTrue(output.length() > 20_000L)
    }

