    private fun fillRect(s: PDPageContentStream, x: Float, top: Float, width: Float, height: Float, color: Color) {
        s.saveGraphicsState()
        s.setNonStrokingColor(color)
        s.addRect(x, H - top - height, width, height)
        s.fill()
        s.restoreGraphicsState()
    }

    private fun strokeRect(s: PDPageContentStream, x: Float, top: Float, width: Float, height: Float, lineWidth: Float) {
        s.saveGraphicsState()
        s.setStrokingColor(Color.BLACK)
        s.setLineWidth(lineWidth)
        s.addRect(x, H - top - height, width, height)
        s.stroke()
        s.restoreGraphicsState()
    }

    private fun hairline(s: PDPageContentStream, x1: Float, top1: Float, x2: Float, top2: Float) {
        s.saveGraphicsState()
        s.setStrokingColor(LINE_COLOR)
        s.setLineWidth(0.35f)
        s.moveTo(x1, H - top1)
        s.lineTo(x2, H - top2)
        s.stroke()
        s.restoreGraphicsState()
    }

